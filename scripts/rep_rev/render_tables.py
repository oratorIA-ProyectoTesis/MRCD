"""Render run_main/results.json (+ historical, post-hoc, utt74) into experimentos/TABLES.md. No computation of new results."""

import json
from pathlib import Path

EXP = Path(r"C:\zArnes-tesis\mrcd\results\ejecucion_material4_20261030\experimentos")
R = json.loads((EXP / "run_main" / "results.json").read_text("utf8"))
H = json.loads((EXP / "historical_fold5.json").read_text("utf8"))
P = json.loads((EXP / "run_main" / "posthoc_diagnostics.json").read_text("utf8"))
U = json.loads((EXP / "utt74_check.json").read_text("utf8"))


def f(x, d=3):
    return "n/a" if x is None or x != x else f"{x:.{d}f}"


def row(name, m):
    ci = m["f1_ci95"]
    return (
        f"| {name} | {m['support_pos']} | {m['n']} | {m['tp']}/{m['fp']}/{m['fn']}/{m['tn']} | {f(m['precision'], 2)} | "
        f"{f(m['recall'], 2)} | {f(m['f1'])} [{f(ci[0], 2)}, {f(ci[1], 2)}] | {m['n_pos_groups']}/{m['n_groups']} |"
    )


HDR = (
    "| model | pos | units | TP/FP/FN/TN | P | R | F1 [95% CI, speaker bootstrap] | speakers pos/total |\n"
    "|---|---|---|---|---|---|---|---|"
)
L = [
    "# Tables (generated by scripts/rep_rev/render_tables.py from run_main/results.json)\n"
]
for task, t in R["tasks"].items():
    L.append(
        f"\n## {task}: {t['n_units']} units, {t['pos']} positive turns, {t['pos_speakers']} positive speakers, gate met: {t['gate_met']}\n"
    )
    for cond in ("A", "B"):
        L.append(f"\n### Condition {cond}\n\n{HDR}")
        c = t["cond"][cond]
        for name in ("rule", "V0", "ctx_LR"):
            if name in c:
                L.append(row(name, c[name]))
        if "Vc" in c:
            L.append(
                row(
                    "Vc (all units; IN-SAMPLE for folds 1-3)",
                    c["Vc"]["all_units_in_sample_for_folds_1_3"],
                )
            )
        if "paired_ctx_minus_rule" in c:
            d = c["paired_ctx_minus_rule"]
            L.append(
                f"\nPaired dF1 ctx_LR - rule: {f(d['delta'])} [{f(d['ci'][0])}, {f(d['ci'][1])}], p_boot {f(d['p_boot'], 4)}"
            )
        for k in (
            "paired_ctx_minus_V0_descriptive",
            "paired_rule_minus_V0_descriptive",
        ):
            if k in c:
                d = c[k]
                L.append(
                    f"\nPaired {k}: {f(d['delta'])} [{f(d['ci'][0])}, {f(d['ci'][1])}] (descriptive)"
                )
        if "Vc" in c:
            L.append(
                f"\nFold-4 units only (Vc-favourable: fold 4 tuned Vc's hyperparameters and thresholds; ctx_LR / rule / V0 on the same units):\n\n{HDR}"
            )
            for k, v in c["Vc"].items():
                if k.startswith("fold4_only") and "paired" not in k:
                    L.append(row(k.replace("fold4_only_", ""), v))
            for k, v in c["Vc"].items():
                if "paired" in k:
                    L.append(
                        f"\n{k}: {f(v['delta'])} [{f(v['ci'][0])}, {f(v['ci'][1])}] (descriptive, {v['n_groups']} speakers)"
                    )
        if "per_official_fold" in c:
            L.append(
                "\nPer official fold F1 (descriptive; each fold's predictions are out-of-fold for ctx_LR; Vc omitted):\n"
            )
            L.append(
                "| fold | "
                + " | ".join(m for m in c["per_official_fold"]["1"])
                + " |\n|---|"
                + "---|" * len(c["per_official_fold"]["1"])
            )
            for fo, v in c["per_official_fold"].items():
                L.append(
                    f"| {fo} | "
                    + " | ".join(
                        f"{f(x['f1'])} ({x['support_pos']} pos)" for x in v.values()
                    )
                    + " |"
                )

L.append(
    "\n## Pre-declared family (Holm over 4): ctx_LR minus simple rule, paired F1 on identical units\n"
)
L.append(
    "| task | cond | dF1 | 95% CI | p_boot | p_Holm | verdict |\n|---|---|---|---|---|---|---|"
)
for x in R["family_holm"]:
    d = x["paired_ctx_minus_rule"]
    L.append(
        f"| {x['task']} | {x['condition']} | {f(d['delta'])} | [{f(d['ci'][0])}, {f(d['ci'][1])}] | {f(x['p_boot'], 4)} | {f(x['p_holm'], 4)} | {x['verdict']} |"
    )

L.append("\n## Error decomposition A vs B (same model type, separate fits)\n")
for task, d in R["decomposition"].items():
    L.append(
        f"\n**{task}**: {d['positives']} positives; visible in frozen ASR {d['visible_in_asr']}; destroyed by ASR {d['destroyed_by_asr']}.\n"
    )
    L.append(
        "| model | F1 A | F1 B | F1 loss | loss on units w/o destroyed positives | residual (destroyed positives) | recall B visible | recall B destroyed | recall A destroyed |\n|---|---|---|---|---|---|---|---|---|"
    )
    for m, x in d["models"].items():
        L.append(
            f"| {m} | {f(x['F1_A'])} | {f(x['F1_B'])} | {f(x['total_loss_A_minus_B'])} | {f(x['text_difference_on_reduced_units'])} | "
            f"{f(x['residual_attributed_to_destroyed_positives'])} | {f(x['recall_B_on_visible'], 2)} | {f(x['recall_B_on_destroyed'], 2)} | {f(x['recall_A_on_destroyed'], 2)} |"
        )

L.append(
    "\n## Recall by sub-type of the human mark (descriptive; turns with the sub-type / detected)\n"
)
for k, v in R["subtype_recall"].items():
    L.append(
        f"- {k}: "
        + "; ".join(f"{s} {x['detected']}/{x['turns']}" for s, x in v.items())
    )

L.append(
    "\n## Calibration (ctx_LR raw score vs cross-fitted Platt; pooled OOF; ECE 10 equal-width bins)\n"
)
L.append(
    "| task | cond | prevalence | Brier of constant prevalence | Brier raw | Brier cal | ECE raw | ECE cal | dBrier raw-cal [CI] | dECE raw-cal [CI] |\n|---|---|---|---|---|---|---|---|---|---|"
)
for task, t in R["tasks"].items():
    for cond in ("A", "B"):
        c = t["cond"][cond].get("calibration")
        if c:
            pr = c["prevalence"]
            L.append(
                f"| {task} | {cond} | {f(pr, 4)} | {f(pr * (1 - pr), 4)} | {f(c['brier_raw'], 4)} | {f(c['brier_cal'], 4)} | {f(c['ece_raw'], 4)} | {f(c['ece_cal'], 4)} | "
                f"{f(c['brier_raw_minus_cal']['delta'], 5)} [{f(c['brier_raw_minus_cal']['ci'][0], 5)}, {f(c['brier_raw_minus_cal']['ci'][1], 5)}] | "
                f"{f(c['ece_raw_minus_cal']['delta'], 5)} [{f(c['ece_raw_minus_cal']['ci'][0], 5)}, {f(c['ece_raw_minus_cal']['ci'][1], 5)}] |"
            )
L.append(
    "\nReliability of the raw score, B condition (bin: n, mean score, observed positive rate):\n"
)
for task in ("rep_literal", "revision"):
    c = R["tasks"][task]["cond"]["B"]["calibration"]
    L.append(
        f"- {task}: "
        + "; ".join(
            f"[{b[0]:.1f},{b[1]:.1f}) n={b[2]} s={f(b[3], 2)} obs={f(b[4], 2)}"
            for b in c["reliability_raw"]
            if b[2]
        )
    )

L.append(
    "\n## Post-hoc shortcut check (annex; length / punctuation / filler-count features only)\n"
)
L.append("| task | cond | shortcut-only F1 [CI] | TP/FP/FN |\n|---|---|---|---|")
for k, v in P.items():
    c = v["shortcut_only_confusion"]
    ci = v["shortcut_only_f1_ci95"]
    t, cond = k.split("|")
    L.append(
        f"| {t} | {cond} | {f(c['f1'])} [{f(ci[0], 2)}, {f(ci[1], 2)}] | {c['tp']}/{c['fp']}/{c['fn']} |"
    )

L.append(
    "\n## Historical fold 5 (copied as is from the earlier frozen evaluation; not used for anything)\n"
)
L.append(
    "| task | model | pos | TP/FP/FN/TN | P | R | F1 [CI] |\n|---|---|---|---|---|---|---|"
)
for task in ("rep_full", "revision"):
    for m, c in H[task].items():
        ci = c["f1_ci95"]
        L.append(
            f"| {task} (earlier-study mark) | {m} | {c['support_pos']} | {c['tp']}/{c['fp']}/{c['fn']}/{c['tn']} | {f(c['precision'], 2)} | {f(c['recall'], 2)} | {f(c['f1'])} [{f(ci[0], 2)}, {f(ci[1], 2)}] |"
        )

L.append("\n## utt74 route check (not an evaluation)\n")
L.append(
    f"- duration {U['duration_s']:.3f} s, zero-padded: {U['zero_padded_to_3s']}; reference: {U['reference_event']}"
)
L.append(f"- frozen-recipe ASR words: {U['asr_words']}")
L.append(
    f"- V0 unit decision: {U['v0_unit_decision']}; rule detectors: {U['rule_detectors']}"
)
for w in U["windows"]:
    L.append(
        f"- window {w['start']:.2f}-{w['end']:.2f}: argmax {w['argmax']}; probs {w['probs']}"
    )
(EXP / "TABLES.md").write_text("\n".join(L) + "\n", encoding="utf8")
print("ok", len(L))
