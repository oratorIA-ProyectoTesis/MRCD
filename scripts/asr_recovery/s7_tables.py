"""Render TABLES.md (all numbers) and ERRORS.md (examples) from run_o1 / run_o2_o3 / family.json."""

import _pin  # noqa: F401  (MUST be first)
import csv
import hashlib
import json

from mrcd.asr_recovery.common import LITERAL_SUBTYPES, OUT, SEED, TASKS, load_pool  # noqa: F401


def f(x, nd=3):
    return "n/a" if x is None or x != x else f"{x:.{nd}f}"


def ci(c):
    return f"[{f(c[0])}, {f(c[1])}]"


def main():
    o1 = json.loads((OUT / "run_o1" / "results.json").read_text("utf8"))
    o23 = json.loads((OUT / "run_o2_o3" / "results.json").read_text("utf8"))
    fam = json.loads((OUT / "family.json").read_text("utf8"))
    L = ["# TABLES (auto-generated by s7_tables.py; EXPLORATORY)\n"]
    # ---- O1
    for task in TASKS:
        t = o1["tasks"][task]
        L.append(
            f"\n## O1 - {task}: {t['pos']} positive turns ({t['pos_speakers']} speakers), {t['neg_sampled']} sampled negatives, P0 control = {t['p0_control']}\n"
        )
        L.append(
            "Sanity: refitted ctx_LR on cached P0 text vs parent OOF mismatches = "
            f"{t['sanity_P0cache_ctx_LR_vs_oof_mismatch']}, vs parent predictions.csv = {t['sanity_P0cache_ctx_LR_vs_parent_mismatch']}.\n"
        )
        L.append("### Survival of the human mark in the ASR text (positives)\n")
        L.append(
            "| variant | survives / n | rate | 95% CI (speaker bootstrap) | gained vs P0 | lost vs P0 | delta rate [95% CI] | of P0-destroyed, now visible |"
        )
        L.append("|---|---|---|---|---|---|---|---|")
        for v, d in t["variants"].items():
            s = d["survival"]
            p = d.get("survival_paired_vs_P0")
            dd = d["survival_on_P0_destroyed"]
            L.append(
                f"| {v} | {int(s['k'])}/{s['n']} | {f(s['rate'])} | {ci(s['ci'])} | "
                + (
                    f"{p['gained']} | {p['lost']} | {f(p['delta'])} {ci(p['ci'])} | "
                    if p
                    else "- | - | - | "
                )
                + f"{dd['recovered']}/{dd['n']} |"
            )
        for m in ("rule", "ctx_LR"):
            L.append(
                f"\n### {m}: weighted F1 on the frame (negatives re-weighted by inverse sampling fraction)\n"
            )
            L.append(
                "| variant | TP/FP/FN/TN (raw) | w-P | w-R | w-F1 [95% CI] | delta w-F1 vs P0 [95% CI] | p (boot) | recall on P0-destroyed | recall on P0-visible | FP on sampled neg (rate) | new FP / removed FP | new TP / lost TP | recovered share of A-P0 |"
            )
            L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
            a = t["A"][m]
            L.append(
                f"| A (reference text) | {a['tp']}/{a['fp']}/{a['fn']}/{a['tn']} | {f(a['w_precision'])} | {f(a['w_recall'])} | {f(a['w_f1'])} | - | - | - | - | - | - | - | - |"
            )
            for v, d in t["variants"].items():
                x = d["models"][m]
                pd = x.get("paired_f1w_vs_P0")
                ch = x.get("changes_vs_P0")
                fp = x["fp_on_sampled_negatives"]
                L.append(
                    f"| {v} | {x['tp']}/{x['fp']}/{x['fn']}/{x['tn']} | {f(x['w_precision'])} | {f(x['w_recall'])} | {f(x['w_f1'])} {ci(x['f1w_ci95'])} | "
                    + (
                        f"{f(pd['delta'])} {ci(pd['ci'])} | {f(pd['p_boot'], 4)} | "
                        if pd
                        else "- | - | "
                    )
                    + f"{f(x['recall_on_P0_destroyed_pos'])} | {f(x['recall_on_P0_visible_pos'])} | {fp['fp']}/{fp['n_neg']} ({f(fp['rate'])}) | "
                    + (
                        f"{ch['new_fp']} / {ch['removed_fp']} | {ch['new_tp']} / {ch['lost_tp']} | {f(x.get('recovered_share_of_A_minus_P0'))} |"
                        if ch
                        else "- | - | - |"
                    )
                )
        L.append(
            "\n### General-ASR damage control (negatives = sampled negatives; WER over normalised tokens)\n"
        )
        L.append(
            "| variant | WER(P0 vs variant) on neg | WER vs reference text A on neg | WER vs ref A on all frame units | empty outputs | prompt echo | mean words/unit |"
        )
        L.append("|---|---|---|---|---|---|---|")
        for v, d in t["variants"].items():
            L.append(
                f"| {v} | {f(d.get('wer_P0_vs_variant_on_neg'))} | {f(d['wer_vs_reference_text_A_on_neg'])} | {f(d['wer_vs_reference_text_A_all'])} | {d['empty_outputs']} | {d['prompt_echo']} | {f(d['mean_words'], 2)} |"
            )
    # ---- O2 / O3
    for task in TASKS:
        t = o23["tasks"][task]
        L.append(
            f"\n## O2 / O3 - {task}: {t['n_units']} units, {t['pos']} positives ({t['pos_speakers']} speakers); visible in ASR {t['visible_pos']}, destroyed {t['destroyed_pos']}\n"
        )
        L.append(
            f"Parity of refitted ctx_LR(B) with parent decisions: {t['parity_mismatch_ctx_LR_B_vs_parent']} mismatches (rule: {t['parity_mismatch_rule_B_vs_parent']}). F1(ctx_LR A) = {f(t['f1']['ctx_LR_A'])}, F1(ctx_LR B) = {f(t['f1']['ctx_LR'])}.\n"
        )
        L.append(
            "| model | TP/FP/FN/TN | P | R | F1 [95% CI] | delta F1 vs ctx_LR(B) [95% CI] | p (boot) | delta vs rule(B) [95% CI] | recall on destroyed | recall on visible | new FP / removed FP | new TP / lost TP | recovered share of A-B (ctx_LR) |"
        )
        L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for n, x in t["models"].items():
            p = x.get("paired_vs_ctx_LR_B")
            r = x.get("paired_vs_rule_B")
            c = x["fp_vs_ctx_LR_B"]
            L.append(
                f"| {n} | {x['tp']}/{x['fp']}/{x['fn']}/{x['tn']} | {f(x['precision'])} | {f(x['recall'])} | {f(x['f1'])} {ci(x['f1_ci95'])} | "
                + (
                    f"{f(p['delta'])} {ci(p['ci'])} | {f(p['p_boot'], 4)} | "
                    if p
                    else "- | - | "
                )
                + (f"{f(r['delta'])} {ci(r['ci'])} | " if r else "- | ")
                + f"{f(x['recall_on_destroyed'])} | {f(x['recall_on_visible'])} | {c['new_fp']} / {c['removed_fp']} | {c['recovered_tp_new']} / {c['lost_tp']} | {f(x.get('recovered_share_of_A_minus_B_ctx_LR'))} |"
            )
    # ---- family
    L.append(
        "\n## Pre-declared family (best variant of each O vs control ctx_LR on B / P0 text), Holm over 6\n"
    )
    L.append(
        "| task | O | best variant | w-F1 | delta F1 [95% CI] | p (boot) | p (Holm) | verdict |"
    )
    L.append("|---|---|---|---|---|---|---|---|")
    for x in fam:
        L.append(
            f"| {x['task']} | {x['O']} | {x['variant']} | {f(x['f1'])} | {f(x['delta'])} {ci(x['ci'])} | {f(x['p_boot'], 4)} | {f(x['p_holm'], 4)} | {x['verdict']} |"
        )
    L.append(
        "\nSelection of the best variant among two is not accounted for by the bootstrap: p-values are optimistic.\n"
    )
    (OUT / "TABLES.md").write_text("\n".join(L) + "\n", "utf8")

    # ---- error examples
    pool = load_pool()
    by = {u["unit_id"]: u for u in pool}
    E = [
        "# ERRORS (auto-generated; deterministic sha256 order, seed 13; no labels created)\n"
    ]
    rows = list(
        csv.DictReader((OUT / "run_o1" / "predictions.csv").open(encoding="utf8"))
    )
    idx = {(r["task"], r["variant"], r["model"], r["unit_id"]): r for r in rows}
    key = lambda s: hashlib.sha256(f"{SEED}|{s}".encode()).hexdigest()
    for task in TASKS:
        for v in ("P1", "P2"):
            for m in ("ctx_LR", "rule"):
                units = sorted(
                    {
                        r["unit_id"]
                        for r in rows
                        if r["task"] == task and r["variant"] == v and r["model"] == m
                    }
                )
                rec, newfp, surv = [], [], []
                for u in units:
                    a, b = idx[(task, "P0", m, u)], idx[(task, v, m, u)]
                    if b["y"] == "1" and a["decision"] == "0" and b["decision"] == "1":
                        rec.append(u)
                    if b["y"] == "0" and a["decision"] == "0" and b["decision"] == "1":
                        newfp.append(u)
                    if b["y"] == "1" and a["survives"] == "0" and b["survives"] == "1":
                        surv.append(u)
                for name, lst in (
                    (f"recovered positives ({m} fires under {v}, not under P0)", rec),
                    ("new false positives", newfp),
                    (
                        "mark became visible (survival gained)"
                        if m == "ctx_LR"
                        else None,
                        surv if m == "ctx_LR" else [],
                    ),
                ):
                    if not name:
                        continue
                    E.append(f"\n## O1 {task} {v} {m}: {name} - total {len(lst)}\n")
                    for u in sorted(
                        lst, key=lambda x: key(f"{task}|{v}|{m}|{name}|{x}")
                    )[:6]:
                        a, b = idx[(task, "P0", m, u)], idx[(task, v, m, u)]
                        marks = [
                            (k["subtype"], k["span"])
                            for k in by[u]["ref"]["rep_marks"]
                            + by[u]["ref"]["rev_marks"]
                        ]
                        E.append(
                            f"* `{u}` y={b['y']} marks={marks}\n  * reference: {by[u]['text_A']}\n  * P0: {a['text']}\n  * {v}: {b['text']}"
                        )
    p23 = list(
        csv.DictReader((OUT / "run_o2_o3" / "predictions.csv").open(encoding="utf8"))
    )
    ix2 = {(r["task"], r["model"], r["unit_id"]): r for r in p23}
    for task in TASKS:
        for mdl in ("O2_C+S", "O3_C+AC_asr", "O3_C+AC_vad", "O3_AC_vad"):
            us = sorted(
                {r["unit_id"] for r in p23 if r["task"] == task and r["model"] == mdl}
            )
            rec = [
                u
                for u in us
                if ix2[(task, mdl, u)]["y"] == "1"
                and ix2[(task, mdl, u)]["decision"] == "1"
                and ix2[(task, "ctx_LR", u)]["decision"] == "0"
            ]
            nfp = [
                u
                for u in us
                if ix2[(task, mdl, u)]["y"] == "0"
                and ix2[(task, mdl, u)]["decision"] == "1"
                and ix2[(task, "ctx_LR", u)]["decision"] == "0"
            ]
            for name, lst in (
                ("recovered positives (fires; ctx_LR(B) did not)", rec),
                ("new false positives", nfp),
            ):
                E.append(f"\n## O2/O3 {task} {mdl}: {name} - total {len(lst)}\n")
                for u in sorted(lst, key=lambda x: key(f"{task}|{mdl}|{name}|{x}"))[:5]:
                    marks = [
                        (k["subtype"], k["span"])
                        for k in by[u]["ref"]["rep_marks"] + by[u]["ref"]["rev_marks"]
                    ]
                    E.append(
                        f"* `{u}` marks={marks}\n  * reference: {by[u]['text_A']}\n  * ASR (B): {by[u]['text_B']}"
                    )
    (OUT / "ERRORS.md").write_text("\n".join(E) + "\n", "utf8")
    print("tables + errors written")


if __name__ == "__main__":
    main()
