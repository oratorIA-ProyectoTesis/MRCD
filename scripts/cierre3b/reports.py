"""Render the 3b markdown tables from the raw JSON. usage: python reports.py cost|live|asr  (reads results/.../3b)."""

import json
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
R = REPO / "results/cierre_oe1_oe3_20261031/3b"
STAGES = [
    "load_prep",
    "asr_p0",
    "asr_p1",
    "acoustic",
    "linguistic",
    "head_v0",
    "head_vc",
    "decision",
    "report",
]


def med(x):
    return float(np.median(x)) if len(x) else None


def rng(x):
    return f"{np.median(x):.2f} ({np.min(x):.2f}-{np.max(x):.2f})" if len(x) else "n/a"


def cost():
    d = json.loads((R / "cost/cost_runs.json").read_text("utf8"))
    runs, meta = d["runs"], d["meta"]
    files = [f["name"] for f in meta["files"]]
    dur = {f["name"]: f["duration_s"] for f in meta["files"]}
    out = [
        "# Cost report (generated by scripts/cierre3b/reports.py cost)",
        "",
        f"Hardware: {json.dumps(meta['hardware'].get('cpu'))}, RAM {meta['hardware'].get('ram_gb')} GB, {meta['hardware']['platform']}, torch {meta['hardware']['torch']}, CPU-only, OMP_NUM_THREADS={meta['hardware']['OMP_NUM_THREADS']}.",
        f"Background CPU before start: {meta['background_start']['system_cpu_pct']} % ; heaviest: {meta['background_start']['heaviest_cpu_s_delta'][:3]}",
        f"Cold start (checkpoint + Whisper small + Vc head load): {meta['cold_start_load_s']['wall']:.2f} s wall, {meta['cold_start_load_s']['cpu']:.2f} s CPU. RSS after load {meta['mem_after_load']['rss_mb']} MB; final peak working set {meta['mem_end']['peak_rss_mb']} MB.",
        f"Rounds: round 0 discarded from statistics (cold), rounds 1..{meta['rounds']} summarised as median (min-max). Staged events equal engine.analyze: {all(meta['staged_events_equal_engine_analyze'].values())} ({len(meta['staged_events_equal_engine_analyze'])} files).",
        "",
    ]
    hdr = (
        "| file | dur s | "
        + " | ".join(STAGES)
        + " | total s | RTF (all stages, 2 ASR profiles) | RTF default path (p0, V0) | CPU/wall |"
    )
    out += [hdr, "|" + "---|" * (len(STAGES) + 6)]
    agg = {s: [] for s in STAGES}
    for f in files:
        rr = [r for r in runs if r["file"] == f and r["round"] >= 1]
        if not rr:
            continue
        if rr[0].get("error"):
            out.append(
                f"| {f} | {dur[f]:.1f} | rejected: `{rr[0]['error']}` (engine needs >= 13 s); load_prep {med([r['stages_s']['load_prep'] for r in rr]) * 1000:.1f} ms |"
                + " |" * (len(STAGES) + 3)
            )
            continue
        row = []
        for s in STAGES:
            v = [r["stages_s"].get(s, 0) for r in rr]
            row.append(rng(v))
            agg[s].append(med(v) / dur[f])
        tot = [sum(r["stages_s"].values()) for r in rr]
        dflt = [
            sum(v for k, v in r["stages_s"].items() if k not in ("asr_p1", "head_vc"))
            for r in rr
        ]
        cpu = [
            sum(r["stages_cpu_s"].values()) / sum(r["stages_s"].values()) for r in rr
        ]
        out.append(
            f"| {f} | {dur[f]:.1f} | "
            + " | ".join(row)
            + f" | {rng(tot)} | {med(tot) / dur[f]:.2f} | {med(dflt) / dur[f]:.2f} | {med(cpu):.2f} |"
        )
    out += [
        "",
        "Per-stage real-time factor (stage seconds per audio second), median over the analysable files:",
        "",
        "| stage | RTF median | min | max |",
        "|---|---|---|---|",
    ]
    for s in STAGES:
        if agg[s]:
            out.append(
                f"| {s} | {med(agg[s]):.4f} | {min(agg[s]):.4f} | {max(agg[s]):.4f} |"
            )
    cold = [r for r in runs if r["round"] == 0 and not r.get("error")]
    warm = [r for r in runs if r["round"] >= 1 and not r.get("error")]
    out += [
        "",
        f"Cold pass (round 0, first time each file/model path runs): median total {med([sum(r['stages_s'].values()) for r in cold]):.1f} s vs warm {med([sum(r['stages_s'].values()) for r in warm]):.1f} s per file. First file of round 0: {sum(cold[0]['stages_s'].values()):.1f} s ({cold[0]['file']}).",
        f"Peak RSS per run (MB, median of rounds >= 1): {med([r['mem']['rss_mb'] for r in warm]):.0f}; process peak working set at the end: {meta['mem_end']['peak_rss_mb']} MB.",
        f"Coverage/errors: {sum(1 for f in files if any(r['file'] == f and r.get('error') for r in runs))} of {len(files)} files rejected as `audio_too_short`; schema errors in generated documents: {sum(r.get('schema_errors', 0) for r in warm)}.",
        f"Background CPU before each round (%): {sorted({r['background_before_round'] for r in runs})}",
        "",
    ]
    e2e = [
        x for x in d["service_e2e"] if x["round"] >= 1 and x["status"] == "completed"
    ]
    byf = {}
    for x in e2e:
        byf.setdefault(x["file"], []).append(x["s"])
    out += [
        "Service end-to-end (`MrcdAnalyzer.analyze_bytes`, default p0 + V0, JSON built and returned), median s per file / RTF:",
        "",
    ]
    out += [
        f"- {f}: {np.median(v):.1f} s, RTF {np.median(v) / dur[f]:.2f}"
        for f, v in byf.items()
    ]
    (R / "cost/COST_REPORT_tables.md").write_text("\n".join(out), "utf8")
    print("\n".join(out))


def live():
    rows = [
        json.loads(l) for l in (R / "live/runs.jsonl").read_text("utf8").splitlines()
    ]
    cfg = json.loads((R / "live/config.json").read_text("utf8"))
    C = ["live_cfg_v1", "live_cfg_v2", "live_cfg_v3"]
    ses = [r for r in rows if r["kind"] == "session"]
    sil = [r for r in rows if r["kind"] != "session"]
    out = ["# live_cfg comparison tables (generated)", ""]
    out += [
        "| config | sessions | tick median s (median of sessions) | tick p95 s | ticks > 0.5 s % | peak RSS MB | latency median/p95 s | sessions diverging (final) | total differing frames | max frames/session | windows w/o row | duplicate rows | finalize s | load-valid runs |",
        "|" + "---|" * 14,
    ]
    S = {}
    for c in C:
        rr = [r for r in ses if r["config"] == c]
        S[c] = {
            "div": sum(r["final_bad"] > 0 for r in rr),
            "bad": sum(r["final_bad"] for r in rr),
            "lost": sum(r["windows_without_row"] for r in rr),
            "dup": sum(r["duplicate_rows"] for r in rr),
            "tick": med([r["tick_s"]["median"] for r in rr]),
            "p95": med([r["tick_s"]["p95"] for r in rr]),
            "rss": max(r["mem_after"]["peak_rss_mb"] for r in rr),
            "lat_med": med([r["latency_s"]["median"] for r in rr]),
            "lat_p95": med([r["latency_s"]["p95"] for r in rr]),
            "n": len(rr),
            "valid": sum(r["load_valid"] for r in rr),
            "complete": all(r["frames_total"] == r["frames_offline"] for r in rr),
        }
        out.append(
            f"| {c} | {len(rr)} | {S[c]['tick']:.3f} | {S[c]['p95']:.3f} | {med([r['tick_over_budget_pct'] for r in rr]):.1f} | {S[c]['rss']} | {S[c]['lat_med']:.2f}/{S[c]['lat_p95']:.2f} | {S[c]['div']}/{len(rr)} | {S[c]['bad']} | {max([r['final_bad'] for r in rr] or [0])} | {S[c]['lost']} | {S[c]['dup']} | {med([r['finalize_s'] for r in rr]):.1f} | {S[c]['valid']}/{len(rr)} |"
        )
    out += [
        "",
        "Per session (committed_bad before finalize / final_bad after): "
        + "; ".join(
            f"{r['seed']}:{r['config'][-2:]}={r['committed_bad']}/{r['final_bad']}"
            for r in ses
        ),
        "",
        "Background CPU % before each session run: "
        + str(sorted(r["background_before"]["system_cpu_pct"] for r in ses)),
        "",
        "Silence scenarios (120 s):",
        "",
        "| scenario | config | rows | windows w/o row | gaps | tick median s |",
        "|---|---|---|---|---|---|",
    ]
    for r in sil:
        out.append(
            f"| {r['kind']} | {r['config']} | {r['n_rows']} | {r['windows_without_row']} | {len(r['gaps'])} | {r['tick_s']['median']:.3f} |"
        )
    # criteria
    v2, v3 = S["live_cfg_v2"], S["live_cfg_v3"]
    s2 = {r["kind"]: r for r in sil if r["config"] == "live_cfg_v2"}
    s3 = {r["kind"]: r for r in sil if r["config"] == "live_cfg_v3"}
    n = len(cfg["seeds"])
    c1 = all(S[c]["n"] == n and S[c]["complete"] for c in C) and len(sil) == 6
    c2 = v2["bad"] > 0 and v3["div"] <= v2["div"] and v3["bad"] <= 0.5 * v2["bad"]
    c3 = (
        abs(v3["lat_med"] - v2["lat_med"]) <= 0.05
        and abs(v3["lat_p95"] - v2["lat_p95"]) <= 0.05
    )
    valid = all(S[c]["valid"] == S[c]["n"] for c in C)
    c4 = (
        valid
        and v3["tick"] <= 1.25 * v2["tick"]
        and v3["p95"] <= 1.25 * v2["p95"]
        and v3["rss"] <= 1.25 * v2["rss"]
    )
    c5 = v3["lost"] == 0 and v3["dup"] == 0
    c6 = all(
        s3[k]["n_rows"] == s2[k]["n_rows"]
        and len(s3[k]["gaps"]) == len(s2[k]["gaps"]) == 0
        for k in s2
    )
    crit = [
        ("C1 completeness", c1),
        ("C2 parity (v2 shows differences AND v3 <= v2, <= 50 % frames)", c2),
        ("C3 latency within 0.05 s", c3),
        (
            "C4 cost (needs load-valid runs)"
            + (
                ""
                if valid
                else " [NOT EVALUABLE: some runs had background CPU >= 15 %]"
            ),
            c4,
        ),
        ("C5 lost/duplicated = 0", c5),
        ("C6 silence equal", c6),
    ]
    out += ["", "## Criteria (rule: docs/LIVE_CFG_V3_DECISION_RULE.md)", ""] + [
        f"- {k}: **{'MET' if v else 'NOT MET'}**" for k, v in crit
    ]
    allmet = all(v for _, v in crit)
    out += [
        "",
        f"**Outcome: {'criteria all met: v3 is a default CANDIDATE pending approval (code default unchanged)' if allmet else 'criteria not all met: default stays live_cfg_v2; v3 stays experimental'}.**",
    ]
    (R / "live/live_tables.md").write_text("\n".join(out), "utf8")
    (R / "live/criteria.json").write_text(
        json.dumps({"criteria": dict(crit), "all_met": allmet, "summary": S}, indent=1),
        "utf8",
    )
    print("\n".join(out))


if __name__ == "__main__":
    {"cost": cost, "live": live}[sys.argv[1]]()
