"""Plan F: render RESULTS_F.md from results_f.json and g4/g4_summary.json. No number is typed by hand: every figure and every
verdict word below is read from the JSON files (the prose around them carries no figure).

    python scripts/plan_f/render_tables.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402

NA = "not_available"


def f(x, nd: int = 3) -> str:
    return NA if x is None else f"{x:.{nd}f}"


def ci(m: dict, nd: int = 3) -> str:
    v = m.get("value", m.get("delta"))
    lo, hi = m.get("ci95", [None, None])
    if v is None:
        return f"{NA} ({m.get('not_available', 'undefined')})"
    return f"{f(v, nd)} [{f(lo, nd)}, {f(hi, nd)}]"


def dci(m: dict, nd: int = 3) -> str:
    v, (lo, hi) = m["delta"], m["ci95"]
    return NA if v is None else f"{v:+.{nd}f} [{lo:+.{nd}f}, {hi:+.{nd}f}]"


def table(head: list[str], rows: list[list[str]]) -> str:
    out = [
        "| " + " | ".join(head) + " |",
        "| " + " | ".join("---" for _ in head) + " |",
    ]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def prf_row(name: str, d: dict) -> list[str]:
    return [
        name,
        ci(d["f1"]),
        ci(d["precision"]),
        ci(d["recall"]),
        f"{d['tp']} / {d['fp']} / {d['fn']} / {d['tn']}",
    ]


def main() -> None:
    R = json.loads((C.OUT / "results_f.json").read_text("utf8"))
    G = None
    gp = C.OUT / "g4" / "g4_summary.json"
    if gp.exists():
        G = json.loads(gp.read_text("utf8"))
    fam, rep, fil, pro = (
        R["holm_family"],
        R["repetition"],
        R["filler"],
        R["prolongation"],
    )
    H1, H2, H3 = (fam[k] for k in sorted(fam))
    L = []
    L.append(
        "# Plan F results: ft_small_v1 ASR profile and decision profile o2026_13 (EXPLORATORY)\n"
    )
    L.append(
        f"Protocol: `PROTOCOL_EXPLORATORY_F.md` (sha256 `{R['protocol_sha256']}`, committed before any decode or metric). "
        f"Aggregates: `results_f.json`. Label of every figure: **{R['label']}**. This is NOT the confirmatory protocol of "
        "`results/confirmatoria_20261107`. 95 % CIs are speaker-cluster percentile bootstrap intervals "
        f"({R['bootstrap']['n_boot']} resamples, seed {R['bootstrap']['seed']}). Tables are generated by "
        "`scripts/plan_f/render_tables.py`; nothing is typed by hand.\n"
    )
    L.append("## Verdicts (Holm family, protocol section 4)\n")
    L.append(
        table(
            ["hypothesis", "delta [95 % CI]", "p_Holm", "verdict"],
            [
                [
                    "HF1 repetition F1 ft_rule - p1_rule",
                    dci(H1),
                    f(H1["p_holm"]),
                    H1["verdict"],
                ],
                [
                    "HF2 repetition F1 ft_rule - p0_rule",
                    dci(H2),
                    f(H2["p_holm"]),
                    H2["verdict"],
                ],
                [
                    f"HF3 filler recall ft_filler - o2026_11, non-inferiority margin {H3['margin']}",
                    dci(H3),
                    f(H3["p_holm"]),
                    H3["verdict"],
                ],
            ],
        )
    )
    L.append(
        f"\nHF1 / HF2 criterion: CI lower > 0 and p_Holm < 0.05. HF3: CI lower > -{H3['margin']} and p_Holm < 0.05. "
        f"Repetition set: {rep['n_turns']} turns of {rep['n_speakers']} speakers, **{rep['n_positive_turns']} positive turns**: "
        "intervals are wide and an unresolved difference is not evidence of equality.\n"
    )
    L.append("## Repetition (turn-level; positive = >= 1 event)\n")
    L.append(
        table(
            ["system", "F1", "precision", "recall", "TP / FP / FN / TN"],
            [prf_row(k, v) for k, v in rep["systems"].items()],
        )
    )
    L.append(
        "\nDescriptive deltas (F1): "
        + "; ".join(
            f"{k.replace('_', ' ')} {dci(v['f1'])}"
            for k, v in rep["descriptive_deltas"].items()
        )
        + ".\n"
    )
    L.append(
        "Repetition candidates (events before the turn-level decision): "
        + ", ".join(f"{k} {v}" for k, v in rep["n_candidates_total"].items())
        + ".\n"
    )
    L.append("## Filler (turn-level; reference: turn has >= 1 DIHANA f mark)\n")
    L.append(
        table(
            ["system", "F1", "precision", "recall", "TP / FP / FN / TN"],
            [prf_row(k, v) for k, v in fil["systems"].items()],
        )
    )
    L.append(
        "\n`o2026_11` is the shipped head and is **in-sample** on these speakers (biased in its favour); `o2026_11_oof` is the "
        "out-of-fold nested-CV reading of the O-campaign.\n"
    )
    L.append(
        "False-positive turn rate (FP turns / reference-negative turns) and filled-pause tokens per 100 reference words on "
        "turns without any f mark:\n"
    )
    ff = fil["false_filler_per_100_words"]
    rows = []
    for k, v in fil["false_positive_turn_rate"].items():
        tk = {"ft_filler": "ft_text"}.get(k, k)
        rows.append([k, ci(v), ci(ff[tk]) if tk in ff else NA])
    L.append(
        table(["system", "false-positive turn rate", "tokens per 100 words"], rows)
    )
    fd = fil["false_filler_deltas"]
    L.append(
        f"\nTokens per 100 words, ft_text - p0_text {dci(fd['ft_text_minus_p0_text'])}; ft_text - p1_text "
        f"{dci(fd['ft_text_minus_p1_text'])}. `o2026_11`: {ff['o2026_11']['not_available']}.\n"
    )
    L.append(
        "Secondary reading (outside the family): filler F1 `ft_filler` minus the comparator, non-inferiority rule delta >= -0.02 and CI upper >= 0.\n"
    )
    L.append(
        table(
            [
                "comparator",
                "delta F1 [95 % CI]",
                "delta precision",
                "delta recall",
                "non-inferior (F1)",
            ],
            [
                [
                    k,
                    dci(v["f1"]),
                    dci(v["precision"]),
                    dci(v["recall"]),
                    str(v["non_inferior_f1"]),
                ]
                for k, v in fil["secondary_filler_f1_ni"].items()
            ],
        )
    )
    L.append(
        "\n## Prolongation (descriptive; the shipped o2026_11 head, not refitted, in-sample)\n"
    )
    L.append(
        table(
            ["system", "F1", "precision", "recall", "TP / FP / FN / TN"],
            [prf_row(k, v) for k, v in pro["systems"].items()],
        )
    )
    d = pro["o2026_13_minus_o2026_11"]
    L.append(
        f"\nDelta F1 (o2026_13 head on FT words - o2026_11 on P0 words) {dci(d['f1'])}; reference positives "
        f"{pro['n_positive_turns']}; degraded (point delta < -0.02): **{pro['degraded']}**.\n"
    )
    L.append("## Latency gate G4 (protocol section 5)\n")
    if G is None:
        L.append(f"G4: {NA} (no `g4/g4_summary.json`).\n")
    else:
        g = G["G4"]
        L.append(
            f"Profile `{g['profile']}`: wait after close, {g['measured_rounds']} measured rounds after 1 cold round discarded; "
            f"**median {g['wait_after_close_median_s']:.2f} s, max {g['wait_after_close_max_s']:.2f} s** against the "
            f"{g['limit_s']:.0f} s limit: **G4 {'PASS' if g['pass'] else 'FAIL'}** (rule: {g['rule']}). Offline RTF median "
            f"{g['rtf_offline_median']}. Measured {g['measured_utc']}.\n"
        )
        rows = []
        for key, v in G.items():
            if "|" not in key:
                continue
            prof, mode = key.split("|")
            rows.append(
                [
                    prof,
                    mode,
                    ", ".join(f"{x:.2f}" for x in v["cold_discarded_s"]),
                    ", ".join(f"{x:.2f}" for x in v["latency_measured_s"]),
                    f"{v['latency_median_s']:.2f}",
                    f"{v['latency_max_s']:.2f}",
                    str(v["all_equal_to_offline"]),
                    ", ".join(f"{x:.1f}" for x in v["background_cpu_pct_before"]),
                    str(v["background_flagged_rounds"]),
                ]
            )
        L.append(
            table(
                [
                    "profile",
                    "mode",
                    "cold (discarded) s",
                    "measured rounds s",
                    "median",
                    "max",
                    "equal to offline",
                    "background CPU % before each measured round",
                    "rounds flagged (>= 20 %)",
                ],
                rows,
            )
        )
        L.append(
            "\nThe incremental rows are the gate metric (wait after close); the offline rows are the whole-file job time. "
            "One non-DIHANA 120 s clip on one machine; no claim beyond it.\n"
        )
    L.append("## Reuse proofs and speed\n")
    idn = R["identity_checks"]
    for k, v in idn.items():
        if "not_available" in v:
            L.append(f"- {k}: {NA} ({v['not_available']}).")
        else:
            t = f"- {k}: {v['turns_in_both']} turns in both; identical text {v['identical_text']}"
            if "identical_text_and_times" in v:
                t += f"; identical text and word times {v['identical_text_and_times']}"
            L.append(t + ".")
    sp = R["asr_speed"]["ft_small_v1_cpu_int8_4_threads"]
    L.append(
        f"- ft_small_v1 decode of this plan: {sp['turns']} turns, {sp['audio_s']} s of audio in {sp['decode_s']} s, RTF {sp['rtf']} "
        f"({R['asr_speed']['caveat']})."
    )
    L.append(
        f"- model.bin sha256 of the converted fine-tune: `{R['environment']['ft_model_bin_sha256']}`.\n"
    )
    L.append("## not_available (with reason)\n")
    for k, v in R["not_available"].items():
        L.append(f"- {k}: {v}.")
    ann = sorted(p.name for p in C.OUT.glob("ANNEX_*.md"))
    L.append("\n## Deviations from the protocol\n")
    L.append(
        "Dated annexes (each with its own hash): "
        + ", ".join(f"`{a}`" for a in ann)
        + ".\n"
        if ann
        else "No annex was written (no deviation recorded at render time).\n"
    )
    L.append("## Limits (protocol section 8, restated)\n")
    L.append(
        "One corpus (telephone, peninsular Spanish, train-information domain) for training and evaluation; the 36 evaluated "
        "speakers are disjoint from the FT training speakers but domain, channel and vocabulary are shared, so every FT gain "
        "is an in-domain upper bound. The Plan B val metrics were seen before this protocol (not an untouched cell). The "
        "shipped o2026_11 heads were fitted on these speakers (in-sample, biased in their favour). Turn-level scoring; the "
        "filler reference rewards emitting any non-lexical filler, not its form. The model weights are not published. "
        "`o2026_13` stays opt-in whatever the outcome.\n"
    )
    L.append("## Reproduce\n")
    L.append(
        "```\nset PYTHONPATH=<worktree> & set OMP_NUM_THREADS=4 & set HF_HUB_OFFLINE=1 & set MRCD_REPO_ROOT=<main checkout>\n"
        "<repo .venv>/python scripts/plan_f/decode_ft.py        (resumable)\n"
        "<repo .venv>/python scripts/plan_f/ft_features.py      (resumable)\n"
        "<repo .venv>/python scripts/plan_f/evaluate_f.py\n"
        "<repo .venv>/python scripts/plan_f/g4_o2026_13.py\n"
        "<repo .venv>/python scripts/plan_f/render_tables.py\n```\n"
    )
    (C.OUT / "RESULTS_F.md").write_text("\n".join(L), "utf8")
    print("wrote RESULTS_F.md")


if __name__ == "__main__":
    main()
